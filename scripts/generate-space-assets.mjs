import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCENE_WIDTH as W, SCENE_HEIGHT as H, SCENE_ORIGIN } from '../src/space/projection.ts';
// 房间外壳是手绘的图层，每张都跟整个场景一样大、透明底，叠在一起就是完整的房间。
// 家具是单独的小图，锚点是它摆在 (0,0,0) 时对准原点的那个像素。
// 这里只读图片尺寸、写素材表；改图之后重新跑一次。
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'public/space/room01');
const LAYERS=['floor','wall','window','curtains','frame'];
// 床拆成后半（床头、枕头）和前半（被子、床尾），床头柜夹在中间，被子才能盖过床头柜。
const FURNITURE={bedBack:{x:1,y:28},bedFront:{x:1,y:32},nightstand:{x:0,y:15},lamp:{x:0,y:21}};
const assets={};
const size=id=>{const b=fs.readFileSync(path.join(dir,`${id}.png`));return {width:b.readUInt32BE(16),height:b.readUInt32BE(20)};};
for(const id of LAYERS){
 const {width,height}=size(id);
 if(width!==W||height!==H)throw Error(`${id}.png 应该是 ${W} × ${H}，现在是 ${width} × ${height}`);
 assets[id]={path:`space/room01/${id}.png`,width,height,anchor:{...SCENE_ORIGIN}};
}
for(const [id,anchor] of Object.entries(FURNITURE))assets[id]={path:`space/room01/${id}.png`,...size(id),anchor};
fs.writeFileSync(path.join(root,'src/space/assets.generated.ts'),`// Generated by scripts/generate-space-assets.mjs. Hand-drawn pixel art layers, 1:1 logical pixels.\nimport type { RoomAsset } from '../types/space.ts';\nexport const ROOM_ASSETS: Readonly<Record<string, RoomAsset>> = ${JSON.stringify(assets,null,2)};\n`);
console.log(`${LAYERS.length} room layers, ${W} × ${H} each; ${Object.keys(FURNITURE).length} furniture.`);
