import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { studio, Pixels, C } from './space-art/pixels.mjs';
import { drawings } from './space-art/furniture.mjs';
import { createRoom01 } from '../src/space/rooms/room01.ts';
import { orderRoomObjects } from '../src/space/depth.ts';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'public/space/room01');fs.mkdirSync(dir,{recursive:true});
const assets={},sprites={};
for(const [id,draw] of Object.entries(drawings)){
 const s=studio();draw(s);const {pixels,anchor}=s.p.crop();
 fs.writeFileSync(path.join(dir,`${id}.png`),pixels.png());
 assets[id]={path:`space/room01/${id}.png`,width:pixels.w,height:pixels.h,anchor};sprites[id]=pixels;
}
fs.writeFileSync(path.join(root,'src/space/assets.generated.ts'),`// Generated by scripts/generate-space-assets.mjs. Original pixel art, 1:1 logical pixels.\nimport type { RoomAsset } from '../types/space.ts';\nexport const ROOM_ASSETS: Readonly<Record<string, RoomAsset>> = ${JSON.stringify(assets,null,2)};\n`);
// Development preview only. The application draws the separate assets at runtime.
const scene=new Pixels(480,320);scene.rect(0,0,480,320,'#d9e7df');
const room=createRoom01(0),ordered=orderRoomObjects(room.objects);
for(const o of ordered){const a=assets[o.assetId],im=sprites[o.assetId],ox=Math.round(240+12*(o.position.x-o.position.y)-a.anchor.x),oy=Math.round(132+4*(o.position.x+o.position.y)-o.position.z-a.anchor.y);for(let y=0;y<im.h;y++)for(let x=0;x<im.w;x++){const i=(y*im.w+x)*4,alpha=im.data[i+3]/255;if(!alpha)continue;const tx=ox+x,ty=oy+y;if(tx<0||ty<0||tx>=480||ty>=320)throw Error(`Scene bounds exceeded by ${o.id}: ${tx},${ty}`);const dst=(ty*480+tx)*4;for(let c=0;c<3;c++)scene.data[dst+c]=Math.round(im.data[i+c]*alpha+scene.data[dst+c]*(1-alpha));scene.data[dst+3]=255;}}
fs.mkdirSync(path.join(root,'docs/space'),{recursive:true});fs.writeFileSync(path.join(root,'docs/space/room01-preview.png'),scene.png());
fs.writeFileSync(path.join(root,'docs/space/palette.json'),JSON.stringify(C,null,2));
console.log(`${Object.keys(assets).length} independent PNG assets; 480 x 320 scene bounds verified.`);
