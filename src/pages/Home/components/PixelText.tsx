/** 一串字画成一张 SVG（高度 = 1em，跟着字号走）；bold 每一点往右多补一格。 */
export function PixelText({ text, bold = false, className }: { text: string; bold?: boolean; className?: string }) {
  const width = 5 + (bold ? 1 : 0), cells: string[] = [];
  let x = 0;
  for (const char of text.toUpperCase()) {
    (GLYPHS[char] || GLYPHS[' ']).forEach((column, index) => {
      for (let y = 0; y < 7; y++) if (column >> y & 1) cells.push(`M${x + index} ${y}h${bold ? 2 : 1}v1h-${bold ? 2 : 1}z`);
    });
    x += width + 1;
  }
  const total = Math.max(1, x - 1);
  return <svg className={className} viewBox={`0 0 ${total} 7`} shapeRendering="crispEdges" fill="currentColor" aria-label={text} role="img"><path d={cells.join('')} /></svg>;
}
